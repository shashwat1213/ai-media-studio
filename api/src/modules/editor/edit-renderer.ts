import { mkdtemp, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runProcess } from '../../lib/run-process.js';
import type { RenderedVideo } from '../generation/motion-renderer.js';
import { buildEditArgs, captionLines } from './edit-filter.js';
import { EDIT_FORMATS, TEXT_SIZES, type EditSpec } from './edit-spec.js';
import { buildAss, groupWords, type AssCaption, type AssCard } from './ass.js';
import { fontBase } from './edit-filter.js';

/** Bundled fonts (SIL OFL, licences next to them). Same path from src/ and dist/. */
export const FONTS_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../../assets/fonts');
export const DEFAULT_FONT = path.join(FONTS_DIR, 'Geist-SemiBold.ttf');

/** Spec captions + karaoke -> the .ass document the renderer burns in. Pure. */
export function specToAss(spec: EditSpec): string | null {
  const { w, h } = EDIT_FORMATS[spec.format];
  const base = fontBase(w, h);
  const captions: AssCaption[] = spec.texts.map((t) => ({
    text: t.text,
    startS: t.startS,
    endS: t.endS,
    x: t.x,
    y: t.y,
    size: Math.round(base * TEXT_SIZES[t.size]),
    color: t.color,
    style: t.style,
    anim: t.anim,
  }));
  const ac = spec.autoCaptions;
  const karaoke =
    ac && ac.words.length
      ? { lines: groupWords(ac.words, { maxWords: ac.maxWords }), y: ac.y, size: Math.round(base * TEXT_SIZES[ac.size]), color: ac.color, highlight: ac.highlight, style: ac.style }
      : null;
  // Card words through libass too (shaping: a Hindi subtitle on a title card must render right).
  const cards: AssCard[] = spec.clips.flatMap((c) =>
    c.kind === 'card'
      ? [{ startS: c.atS, endS: c.atS + c.lengthS, title: c.card.title, subtitle: c.card.subtitle, color: c.card.color, titleSize: Math.round(base * 0.09), subtitleSize: Math.round(base * 0.045) }]
      : [],
  );
  if (!captions.length && !karaoke && !cards.length) return null;
  return buildAss(w, h, captions, karaoke, cards);
}

export interface EditRenderRequest {
  spec: EditSpec;
  /** Fetch clip i's source into `filePath` (the worker streams it from storage). */
  fetchClip: (index: number, filePath: string) => Promise<void>;
  /** Fetch audio track i into `filePath`. */
  fetchAudio?: (index: number, filePath: string) => Promise<void>;
  signal?: AbortSignal;
}

export interface EditRenderer {
  readonly name: string;
  render(req: EditRenderRequest): Promise<RenderedVideo>;
}

/**
 * Renders an EditSpec with ffmpeg. Everything happens in a private temp dir that is always
 * removed. Captions are written to files (one per line) so user text never reaches the command
 * line or the filter graph.
 */
export function createEditRenderer(opts: { ffmpegPath?: string; fontFile?: string; timeoutMs?: number } = {}): EditRenderer {
  const bin = opts.ffmpegPath ?? 'ffmpeg';
  const fontFile = opts.fontFile ?? DEFAULT_FONT;
  const fontsDir = path.dirname(fontFile);
  const timeoutMs = opts.timeoutMs ?? 300_000;

  return {
    name: 'ffmpeg-editor',
    async render({ spec, fetchClip, fetchAudio, signal }) {
      const dir = await mkdtemp(path.join(tmpdir(), 'edit-'));
      try {
        const clipFiles = spec.clips.map((_, i) => path.join(dir, `clip${i}`));
        // Sequential: bounded memory/disk pressure, and the S3 client is already pooled.
        // Cards are generated by ffmpeg itself: nothing to fetch.
        for (let i = 0; i < clipFiles.length; i++) if (spec.clips[i]!.kind !== 'card') await fetchClip(i, clipFiles[i]!);

        // Every line of user text goes to its own file (never into the command line).
        const writeLines = (prefix: string, text: string) =>
          Promise.all(
            captionLines(text).map(async (line, j) => {
              const f = path.join(dir, `${prefix}_${j}.txt`);
              await writeFile(f, line, 'utf8');
              return f;
            }),
          );
        const textFiles = await Promise.all(spec.texts.map((t, i) => writeLines(`t${i}`, t.text)));
        const cardFiles = await Promise.all(
          spec.clips.map(async (c, i) =>
            c.kind === 'card' ? { title: await writeLines(`k${i}t`, c.card.title), subtitle: await writeLines(`k${i}s`, c.card.subtitle) } : null,
          ),
        );
        const audioFiles = spec.audio.map((_, i) => path.join(dir, `audio${i}`));
        if (fetchAudio) for (let i = 0; i < audioFiles.length; i++) await fetchAudio(i, audioFiles[i]!);
        // Captions + karaoke go through libass (shaping, wrapping, Hindi). User text lives only in this file.
        const ass = specToAss(spec);
        const assFile = ass ? path.join(dir, 'captions.ass') : undefined;
        if (ass && assFile) await writeFile(assFile, ass, 'utf8');
        const output = path.join(dir, 'out.mp4');
        await runProcess(
          bin,
          buildEditArgs(spec, { clipFiles, textFiles, cardFiles, audioFiles: fetchAudio ? audioFiles : [], assFile, fontsDir: fontsDir, fontFile, output }),
          { timeoutMs, signal },
        );

        if ((await stat(output)).size === 0) throw new Error('ffmpeg produced an empty file');
        const data = await readFile(output);
        const { w, h } = EDIT_FORMATS[spec.format];
        return { data, mimeType: 'video/mp4', width: w, height: h, durationMs: Math.round(spec.totalS * 1000) };
      } finally {
        await rm(dir, { recursive: true, force: true });
      }
    },
  };
}
