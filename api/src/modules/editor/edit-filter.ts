import { EDIT_FORMATS, EDIT_FPS, TEXT_SIZES, type EditSpec, type ImageMotion, type SpecClip } from './edit-spec.js';

/**
 * Builds the ffmpeg command for one EditSpec. Pure function (no I/O), so the exact command is
 * unit-tested without ffmpeg, and the renderer just runs what this returns.
 *
 * Pipeline:
 *   each clip  -> its own chain, normalised to the output size / 30 fps / yuv420p / exact length:
 *                 - image: fit (contain = bars in the background colour, cover = crop), optional
 *                   Ken Burns move (zoompan on a 2x canvas so slow moves don't stair-step)
 *                 - video: fit, trimmed on the input side
 *                 - card:  generated colour/gradient + title/subtitle that fade in
 *   all clips  -> xfade chain (each transition overlaps the neighbours) or a plain concat
 *   overlays   -> drawbox (highlights), then drawtext (captions) with fade/slide animation
 *
 * Safety: user text never goes into the command line or the filter string. Every caption/card
 * line is written to its own file and read with `textfile=` + `expansion=none`, so characters
 * like ' : , % \ are just characters (no filtergraph or %{...} injection). Colours are validated
 * #RRGGBB, numbers are numbers.
 */

export interface EditInputs {
  /** Local file per clip (same order as spec.clips). Ignored for cards. */
  clipFiles: string[];
  /** Local file per audio track (same order as spec.audio). */
  audioFiles?: string[];
  /** libass subtitle file (captions + karaoke) and the folder with its fonts. */
  assFile?: string;
  fontsDir?: string;
  /** Local files per caption, ONE PER LINE (same order as spec.texts). See captionLines(). */
  textFiles: string[][];
  /** Per clip: the card's title/subtitle line files (null for non-cards). */
  cardFiles: ({ title: string[]; subtitle: string[] } | null)[];
  fontFile: string;
  output: string;
}

/** A caption's lines, each written to its own file by the renderer. */
export const captionLines = (text: string) => (text ? text.split('\n') : []);

/** Caption/card animation length. */
export const ANIM_S = 0.35;

const r3 = (n: number) => String(Math.round(n * 1000) / 1000);
const colorOf = (hex: string, alpha = 1) => `0x${hex.slice(1)}${alpha < 1 ? `@${alpha}` : ''}`;
/** Paths go inside a filter option: escape the filtergraph specials. Our temp paths are tame, but be strict. */
const filterPath = (p: string) => `'${p.replace(/\\/g, '/').replace(/'/g, "'\\''")}'`;

/** Font size base: the SHORT side, so 9:16 captions aren't twice as big as 16:9 ones. Same rule in the web preview. */
export const fontBase = (w: number, h: number) => Math.min(w, h);

/** zoompan expressions per move; `E` = eased 0..1 progress. Zoom is gentle (≤ 15%): this is screen content. */
function motionExpr(m: ImageMotion): { z: string; x: string; y: string } {
  const cx = 'iw/2-(iw/zoom/2)';
  const cy = 'ih/2-(ih/zoom/2)';
  switch (m) {
    case 'zoom-in':
      return { z: '1+0.15*E', x: cx, y: cy };
    case 'zoom-out':
      return { z: '1.15-0.15*E', x: cx, y: cy };
    case 'pan-left':
      return { z: '1.12', x: '(iw-iw/zoom)*(1-E)', y: cy };
    case 'pan-right':
      return { z: '1.12', x: '(iw-iw/zoom)*E', y: cy };
    case 'pan-up':
      return { z: '1.12', x: cx, y: '(ih-ih/zoom)*(1-E)' };
    case 'pan-down':
      return { z: '1.12', x: cx, y: '(ih-ih/zoom)*E' };
    default:
      return { z: '1', x: '0', y: '0' };
  }
}

/** alpha expression: fade in at `s`, fade out at `e`. */
const fadeAlpha = (s: number, e: number, d = ANIM_S) =>
  `if(lt(t,${r3(s)}),0,if(lt(t,${r3(s + d)}),(t-${r3(s)})/${r3(d)},if(gt(t,${r3(e - d)}),max(0,(${r3(e)}-t)/${r3(d)}),1)))`;

export function buildEditArgs(spec: EditSpec, io: EditInputs): string[] {
  const { w, h } = EDIT_FORMATS[spec.format];
  const bg = colorOf(spec.background);
  const args: string[] = ['-hide_banner', '-loglevel', 'error', '-nostdin', '-y'];

  // ---- inputs ----
  spec.clips.forEach((c, i) => {
    const len = r3(c.lengthS);
    if (c.kind === 'card') {
      // Generated by ffmpeg itself (lavfi): a solid colour or a slowly drifting diagonal gradient.
      const src =
        c.card.bg2 && c.card.bg2.toLowerCase() !== c.card.bg.toLowerCase()
          ? `gradients=s=${w}x${h}:c0=${colorOf(c.card.bg)}:c1=${colorOf(c.card.bg2)}:x0=0:y0=0:x1=${w}:y1=${h}:speed=0.004:r=${EDIT_FPS}:d=${len}`
          : `color=c=${colorOf(c.card.bg)}:s=${w}x${h}:r=${EDIT_FPS}:d=${len}`;
      args.push('-f', 'lavfi', '-i', src);
    } else if (c.kind === 'image') {
      // Still + motion: ONE input frame, zoompan emits every output frame. Still, no motion: loop it.
      if (c.motion !== 'none') args.push('-i', io.clipFiles[i]!);
      else args.push('-loop', '1', '-framerate', String(EDIT_FPS), '-t', len, '-i', io.clipFiles[i]!);
    } else {
      // Input-side seek (-ss before -i) is fast; -t limits how much is read.
      args.push('-ss', r3(c.startS), '-t', len, '-i', io.clipFiles[i]!);
    }
  });

  // Audio files go after the clip inputs: input index = clips.length + i (see audioGraph).
  for (const f of io.audioFiles ?? []) args.push('-i', f);

  const chains: string[] = [];
  const base = fontBase(w, h);

  // ---- one chain per clip ----
  spec.clips.forEach((c, i) => {
    const parts: string[] = [];
    if (c.kind === 'card') {
      // With libass, card words are part of the .ass file (drawn on the joined video, shaped).
      if (!io.assFile) parts.push(...cardText(c, io.cardFiles[i] ?? { title: [], subtitle: [] }, h, base, io.fontFile));
    } else {
      const motion = c.kind === 'image' ? c.motion : 'none';
      // Moving stills are framed on a 2x canvas: zoompan moves in whole pixels, so at 1x a slow
      // pan visibly stair-steps. 2x halves the step; 4x (used by Motion) is too slow at 1080p.
      const k = motion === 'none' ? 1 : 2;
      const W = w * k;
      const H = h * k;
      parts.push(
        c.fit === 'cover'
          ? `scale=${W}:${H}:force_original_aspect_ratio=increase:flags=lanczos,crop=${W}:${H}`
          : `scale=${W}:${H}:force_original_aspect_ratio=decrease:flags=lanczos,pad=${W}:${H}:(ow-iw)/2:(oh-ih)/2:color=${bg}`,
      );
      if (motion !== 'none') {
        const frames = Math.max(2, Math.round(c.lengthS * EDIT_FPS));
        const t = `(on/${frames - 1})`;
        const eased = `(${t}*${t}*(3-2*${t}))`;
        const e = motionExpr(motion);
        const sub = (s: string) => s.replaceAll('E', eased);
        parts.push(`zoompan=z='${sub(e.z)}':x='${sub(e.x)}':y='${sub(e.y)}':d=${frames}:s=${w}x${h}:fps=${EDIT_FPS}`);
      }
    }
    parts.push(
      'setsar=1',
      `fps=${EDIT_FPS}`,
      'format=yuv420p',
      // Exact length: pad a too-short source by holding its last frame, then cut.
      `tpad=stop_mode=clone:stop_duration=${r3(c.lengthS)}`,
      `trim=duration=${r3(c.lengthS)}`,
      'setpts=PTS-STARTPTS',
      // xfade needs identical timebases on both inputs...
      'settb=AVTB',
      // ...and (ffmpeg 7) a declared constant frame rate: settb drops it, so set it again.
      `fps=${EDIT_FPS}`,
    );
    chains.push(`[${i}:v]${parts.join(',')}[c${i}]`);
  });

  // ---- join: xfade chain (overlapping) or concat ----
  const n = spec.clips.length;
  if (n === 1) {
    chains.push('[c0]null[base]');
  } else if (spec.transition === 'none' || spec.transitionS <= 0) {
    chains.push(`${spec.clips.map((_, i) => `[c${i}]`).join('')}concat=n=${n}:v=1:a=0[base]`);
  } else {
    let prev = 'c0';
    for (let i = 1; i < n; i++) {
      const out = i === n - 1 ? 'base' : `x${i}`;
      // offset = when clip i starts on the output timeline (the overlap is already in atS).
      chains.push(`[${prev}][c${i}]xfade=transition=${spec.transition}:duration=${r3(spec.transitionS)}:offset=${r3(spec.clips[i]!.atS)}[${out}]`);
      prev = out;
    }
  }

  // ---- overlays on the joined video. Boxes first so captions sit on top ----
  const overlays: string[] = [];
  const thick = Math.max(4, Math.round(base * 0.006));
  for (const b of spec.boxes) {
    overlays.push(
      `drawbox=x=${Math.round(b.x * w)}:y=${Math.round(b.y * h)}:w=${Math.round(b.w * w)}:h=${Math.round(b.h * h)}` +
        `:color=${colorOf(b.color)}:t=${thick}:enable='between(t,${r3(b.startS)},${r3(b.endS)})'`,
    );
  }
  // Captions: libass when an .ass file is given (shaping, wrapping, Hindi, karaoke), else the
  // drawtext path (kept for unit tests of the legacy shape and as a fallback).
  if (io.assFile) {
    overlays.push(`ass=${filterPath(io.assFile)}${io.fontsDir ? `:fontsdir=${filterPath(io.fontsDir)}` : ''}`);
  } else spec.texts.forEach((t, i) => {
    const size = Math.round(base * TEXT_SIZES[t.size]);
    const pad = Math.round(size * 0.4);
    const margin = Math.round(base * 0.02);
    const lines = io.textFiles[i] ?? [];
    // One drawtext PER LINE: ffmpeg 8 draws '\n' inside a text file as a missing-glyph box, and
    // separate lines also centre individually (like subtitles). y_align=font gives every line the
    // same text_h (font ascent+descent), so `text_h` below is a constant and lines stack evenly.
    const gap = t.style === 'box' ? 2 * pad : Math.round(size * 0.2);
    const block = `(${lines.length}*text_h+${lines.length - 1}*${gap})`;
    // Keep the WHOLE thing on screen, including the box padding: ffmpeg silently skips a box
    // that would cross the frame edge.
    const edge = margin + (t.style === 'box' ? pad : 0);
    const top = `max(${edge},min(h-${block}-${edge},${r3(t.y)}*h-${block}/2))`;
    const x = `max(${edge},min(w-text_w-${edge},${r3(t.x)}*w-text_w/2))`;
    // 'slide' rises ~4% of the frame while fading in.
    const rise = t.anim === 'slide' ? `+${Math.round(h * 0.04)}*max(0,1-(t-${r3(t.startS)})/${ANIM_S})` : '';
    const alpha = t.anim === 'none' ? '' : `:alpha='${fadeAlpha(t.startS, t.endS)}'`;
    const style =
      t.style === 'box'
        ? `:box=1:boxcolor=0x000000@0.7:boxborderw=${pad}`
        : t.style === 'outline'
          ? `:borderw=${Math.max(2, Math.round(size * 0.08))}:bordercolor=0x000000`
          : `:shadowx=2:shadowy=2:shadowcolor=0x000000@0.6`;
    lines.forEach((file, li) => {
      overlays.push(
        `drawtext=fontfile=${filterPath(io.fontFile)}:textfile=${filterPath(file)}:expansion=none` +
          `:fontsize=${size}:fontcolor=${colorOf(t.color)}:y_align=font` +
          `:x='${x}':y='${top}+${li}*(text_h+${gap})${rise}'${style}${alpha}:enable='between(t,${r3(t.startS)},${r3(t.endS)})'`,
      );
    });
  });
  chains.push(overlays.length ? `[base]${overlays.join(',')}[out]` : '[base]null[out]');

  // ---- audio ----
  const audio = audioGraph(spec, (io.audioFiles ?? []).length);
  chains.push(...audio.chains);

  args.push(
    '-filter_complex', chains.join(';'),
    '-map', '[out]',
    ...(audio.out ? ['-map', `[${audio.out}]`, '-c:a', 'aac', '-b:a', '160k', '-ar', '48000'] : []),
    '-t', r3(spec.totalS),
    '-r', String(EDIT_FPS),
    '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '23',
    '-pix_fmt', 'yuv420p',
    // moov atom at the front: the browser can start playing before the whole file arrives.
    '-movflags', '+faststart',
    ...(audio.out ? [] : ['-an']),
    io.output,
  );
  return args;
}

const AFMT = 'aformat=sample_rates=48000:channel_layouts=stereo';
/** Ducking: music drops ~10 dB while the voice speaks, back within ~0.35 s (measured). */
export const DUCK = 'threshold=0.005:ratio=20:attack=15:release=350:knee=1';

/**
 * Audio: every sound source placed on the output timeline, then mixed.
 *  - video clips with sound: their trimmed sound at the clip's position
 *  - tracks (voice-over / music): trimmed, delayed to `atS`, volume
 *  - ducking: tracks marked `duck` are side-chain compressed by the sum of the NON-ducked
 *    sources (the voice), so music dips under narration automatically
 * Returns no output at all when nothing makes a sound (silent MP4, like before).
 */
export function audioGraph(spec: EditSpec, audioInputs: number): { chains: string[]; out: string | null } {
  const T = r3(spec.totalS);
  const place = (input: string, startS: number, lengthS: number, atS: number, volume: number, label: string) =>
    `[${input}]${AFMT},atrim=start=${r3(startS)}:duration=${r3(lengthS)},asetpts=PTS-STARTPTS,volume=${volume},` +
    `adelay=${Math.round(atS * 1000)}:all=1,apad=whole_dur=${T}[${label}]`;

  const chains: string[] = [];
  const voice: string[] = [];
  const ducked: string[] = [];
  spec.clips.forEach((c, i) => {
    if (c.kind === 'video' && c.volume > 0) {
      // The clip's sound starts at its trim and plays for the clip's length (input-side -ss already applied).
      chains.push(place(`${i}:a`, 0, c.lengthS, c.atS, c.volume, `ca${i}`));
      voice.push(`ca${i}`);
    }
  });
  spec.audio.forEach((a, i) => {
    if (i >= audioInputs || a.volume <= 0) return;
    chains.push(place(`${spec.clips.length + i}:a`, a.startS, a.lengthS, a.atS, a.volume, `ta${i}`));
    (a.duck ? ducked : voice).push(`ta${i}`);
  });
  if (!voice.length && !ducked.length) return { chains: [], out: null };

  let sources = [...voice];
  if (ducked.length && voice.length) {
    // The side-chain key = all non-ducked sources mixed; each voice source is split so it can
    // feed both the key and the final mix.
    const keyIn: string[] = [];
    sources = voice.map((v) => {
      chains.push(`[${v}]asplit=2[${v}m][${v}k]`);
      keyIn.push(`[${v}k]`);
      return `${v}m`;
    });
    chains.push(keyIn.length > 1 ? `${keyIn.join('')}amix=inputs=${keyIn.length}:normalize=0[key]` : `${keyIn[0]}anull[key]`);
    if (ducked.length > 1) {
      chains.push(`[key]asplit=${ducked.length}${ducked.map((_, j) => `[key${j}]`).join('')}`);
      ducked.forEach((d, j) => {
        chains.push(`[${d}][key${j}]sidechaincompress=${DUCK}[${d}d]`);
        sources.push(`${d}d`);
      });
    } else {
      chains.push(`[${ducked[0]}][key]sidechaincompress=${DUCK}[${ducked[0]}d]`);
      sources.push(`${ducked[0]}d`);
    }
  } else {
    sources.push(...ducked);
  }
  const mix = sources.length > 1 ? `${sources.map((x) => `[${x}]`).join('')}amix=inputs=${sources.length}:duration=longest:normalize=0,` : `[${sources[0]}]`;
  // A limiter keeps summed sources from clipping; atrim pins the exact length.
  chains.push(`${mix}alimiter=limit=0.95:level=disabled,atrim=duration=${T}[aout]`);
  return { chains, out: 'aout' };
}

/** Title (big) + subtitle (smaller), centred as one block, fading/rising in. */
function cardText(c: Extract<SpecClip, { kind: 'card' }>, files: { title: string[]; subtitle: string[] }, h: number, base: number, font: string): string[] {
  const tSize = Math.round(base * 0.09);
  const sSize = Math.round(base * 0.045);
  const gapT = Math.round(tSize * 0.25);
  const gapS = Math.round(sSize * 0.3);
  const between = files.title.length && files.subtitle.length ? Math.round(base * 0.04) : 0;
  const blockH = files.title.length * tSize + Math.max(0, files.title.length - 1) * gapT + between + files.subtitle.length * sSize + Math.max(0, files.subtitle.length - 1) * gapS;
  let y = Math.round((h - blockH) / 2);
  const rise = `+${Math.round(h * 0.03)}*max(0,1-t/0.5)`;
  const out: string[] = [];
  const line = (file: string, size: number, color: string, alphaMax: number, delay: number) =>
    `drawtext=fontfile=${filterPath(font)}:textfile=${filterPath(file)}:expansion=none:fontsize=${size}:fontcolor=${colorOf(color)}` +
    `:y_align=font:x='(w-text_w)/2':y='${y}${rise}':alpha='${alphaMax}*min(1,max(0,(t-${delay})/0.5))'`;
  // y_align=font: each line's box is ~1.2x the font size; step by the size + gap (close enough, and constant).
  for (const f of files.title) {
    out.push(line(f, tSize, c.card.color, 1, 0.1));
    y += tSize + gapT;
  }
  y += between - (files.title.length ? gapT : 0);
  for (const f of files.subtitle) {
    out.push(line(f, sSize, c.card.color, 0.85, 0.35));
    y += sSize + gapS;
  }
  return out.length ? out : ['null'];
}
